"""Render BENCH.md from results/*.json. Every number comes from a run file; none is typed."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "BENCH.md"
COLUMNS = [
    ("Scenario", lambda r: r["scenario"]),
    ("Engine", lambda r: f"{r['engine']} + {r['model']}" if r.get("model") else r["engine"]),
    ("Seed", lambda r: r["seed"]),
    ("Orders", lambda r: r["summary"]["orders"]),
    ("Delivered", lambda r: r["summary"]["delivered"]),
    ("Within promise", lambda r: r["summary"]["deliveredWithinPromise"]),
    ("Cancelled", lambda r: r["summary"]["cancelled"]),
    ("Consistent", lambda r: f"{r['summary']['consistent']}/{r['summary']['orders']}"),
    (
        "Mean min",
        lambda r: r["summary"]["meanMinutes"] if r["summary"]["meanMinutes"] is not None else "-",
    ),
    (
        "p95 min",
        lambda r: r["summary"]["p95Minutes"] if r["summary"]["p95Minutes"] is not None else "-",
    ),
    ("Recovery decisions", lambda r: r["summary"]["recoveryDecisions"]),
    ("Human prompts", lambda r: r["summary"]["humanPrompts"]),
    ("LLM calls, decisions", lambda r: _role(r, "decision")),
    ("LLM calls, perception", lambda r: _role(r, "perception")),
    ("LLM calls, language", lambda r: _role(r, "language")),
    ("World calls", lambda r: r["summary"].get("worldCalls", 0)),
    ("LLM tokens", lambda r: r["summary"].get("llmTokens", 0)),
    ("Cost (USD)", lambda r: r["summary"]["cost"] if r["summary"].get("llmPriced") else "unpriced"),
    ("Planner ms", lambda r: r.get("timing", {}).get("planningMs", "-")),
    ("Model ms, decisions", lambda r: r.get("timing", {}).get("modelMs", "-")),
    ("Re-plans", lambda r: r["summary"].get("replans", "-")),
    (
        "Plan steps",
        lambda r: (
            r["summary"]["meanPlanSteps"] if r["summary"].get("meanPlanSteps") is not None else "-"
        ),
    ),
    ("Wall s", lambda r: r.get("timing", {}).get("wallSeconds", "-")),
    ("Not recovered", lambda r: ", ".join(r["summary"]["unrecovered"]) or "-"),
]


def _role(run: dict, role: str) -> int:
    roles = run["summary"].get("llmCallsByRole")
    if roles is None:  # a file from before the roles: every call counted as a decision
        return run["summary"]["llmCalls"] if role == "decision" else 0
    return roles[role]


README = ROOT / "README.md"
START, END = "<!-- bench:start -->", "<!-- bench:end -->"


def table_lines(runs: list[dict]) -> list[str]:
    lines = [
        "| " + " | ".join(name for name, _ in COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    ordered = sorted(
        runs, key=lambda r: (r["scenario"], r["engine"], str(r.get("model")), r["seed"])
    )
    for run in ordered:
        lines.append("| " + " | ".join(str(fn(run)) for _, fn in COLUMNS) + " |")
    if not runs:
        lines.append("| (no runs yet) |" + " |" * (len(COLUMNS) - 1))
    return lines


def embed(readme_text: str, runs: list[dict]) -> str:
    """Replace the table between the bench markers in the README; leave everything else alone."""
    if START not in readme_text or END not in readme_text:
        return readme_text
    before, rest = readme_text.split(START, 1)
    _, after = rest.split(END, 1)
    body = "\n".join(table_lines(runs))
    return f"{before}{START}\n{body}\n{END}{after}"


def render(results_dir: Path = RESULTS) -> str:
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(results_dir.glob("*.json"))]
    lines = [
        "# Bench",
        "",
        "One row per run of a scenario against an engine under a seed, generated by",
        "`make bench-table` from the files in `results/`; do not edit by hand. A run is",
        "`uv run foood bench --scenario <name> --engine <name> --seed <n>` on the frozen",
        "clock with the headless autopilots, so the same inputs give the same numbers for an",
        "engine without a model; a model's choices can vary between runs, which is part of",
        "the point. Cost is priced with the prices each run file records (per model when the",
        "run names them); tokens are always counted. Planner ms is the wall-clock of every",
        "planning round (first plans, re-plans and the rounds where the world ran ahead of the",
        "plan) as the engine's tracer measured it; Model ms is the round trip of the model",
        "calls that decide about an order, measured around each call (perception and",
        "language calls are timed the same way and kept in the files); Plan steps is the",
        "mean length of first plans; Wall s is the real time the run took on the machine",
        "named in its file.",
        "",
        "Honesty notes: the scenarios and the seed list are committed before a run; every",
        "number is read from a results file; the hand-wired rows are reported as they are;",
        "an engine that calls a model is labelled with it and shown per seed, so its",
        "variation is visible rather than averaged away; model calls that decide about an",
        "order are counted apart from the ones that only write language (messages,",
        "intake), which any engine may use; nothing is priced unless prices were set.",
        "",
        *table_lines(runs),
        "",
        f"{len(runs)} run(s).",
    ]
    for run in sorted(runs, key=lambda r: (r["scenario"], r["engine"], r["seed"])):
        lines.append("| " + " | ".join(str(fn(run)) for _, fn in COLUMNS) + " |")
    if not runs:
        lines.append("| (no runs yet) |" + " |" * (len(COLUMNS) - 1))
    lines += ["", f"{len(runs)} run(s)."]
    priced = sorted(
        {
            (r["llmPrices"]["inputPerMillionUsd"], r["llmPrices"]["outputPerMillionUsd"])
            for r in runs
            if r.get("summary", {}).get("llmPriced")
            and r.get("llmPrices")
            and r["llmPrices"]["inputPerMillionUsd"] is not None
        }
    )
    per_model: dict[str, tuple[float, float]] = {}
    for r in runs:
        for name, entry in (r.get("llmPrices", {}).get("perModel") or {}).items():
            per_model[name] = (entry["in"], entry["out"])
    if priced or per_model:
        parts = [f"{name}: {i} in and {o} out" for name, (i, o) in sorted(per_model.items())]
        parts += [f"{i} in and {o} out" for i, o in priced]
        lines += [
            "",
            "Costs use the model prices each run file records: "
            + "; ".join(parts)
            + ", USD per million tokens (see `bench.env` for the source and date).",
        ]
    sets = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted((results_dir / "repeats").glob("*.json"))
    ]
    if sets:
        lines += [
            "",
            "## Repeats",
            "",
            "The same scenario, engine and seed run several times, so the model is the only",
            "source of variation; an engine without a model is the control and its runs must",
            "be identical. Histograms read value ×count.",
            "",
            "| " + " | ".join(name for name, _ in REPEAT_COLUMNS) + " |",
            "|" + "|".join("---" for _ in REPEAT_COLUMNS) + "|",
        ]
        for one in sorted(sets, key=lambda r: (r["scenario"], r["engine"], r["seed"])):
            lines.append("| " + " | ".join(str(fn(one)) for _, fn in REPEAT_COLUMNS) + " |")
        lines += ["", f"{len(sets)} set(s)."]
    return "\n".join(lines) + "\n"


def _deciding(repeated: dict) -> dict:
    """The decision calls per run, as a histogram; ``distribution.llmCalls`` counts every role."""
    runs = repeated.get("runs") or []
    if not runs or any("llmCallsByRole" not in run for run in runs):
        return repeated["distribution"]["llmCalls"]  # a file from before the roles
    out: dict[str, int] = {}
    for run in runs:
        key = str(run["llmCallsByRole"].get("decision", 0))
        out[key] = out.get(key, 0) + 1
    return dict(sorted(out.items(), key=lambda kv: int(kv[0])))


def _counts(histogram: dict) -> str:
    return ", ".join(f"{value} ×{count}" for value, count in histogram.items()) or "-"


def _triple(spread: dict | None) -> str:
    return "-" if not spread else f"{spread['min']} / {spread['median']} / {spread['max']}"


REPEAT_COLUMNS = [
    ("Scenario", lambda r: r["scenario"]),
    ("Engine", lambda r: f"{r['engine']} + {r['model']}" if r.get("model") else r["engine"]),
    ("Seed", lambda r: r["seed"]),
    ("Runs", lambda r: r["times"]),
    ("Delivered", lambda r: _counts(r["distribution"]["delivered"])),
    ("LLM calls, decisions", lambda r: _counts(_deciding(r))),
    ("LLM calls, all", lambda r: _counts(r["distribution"]["llmCalls"])),
    ("Human prompts", lambda r: _counts(r["distribution"]["humanPrompts"])),
    ("Decisions taken", lambda r: _counts(r["distribution"]["decisionsTaken"])),
    ("Model ms (min / median / max)", lambda r: _triple(r["distribution"]["modelMs"])),
    (
        "Cost (USD)",
        lambda r: (
            _triple(r["distribution"]["cost"]) if r["distribution"].get("llmPriced") else "unpriced"
        ),
    ),
    ("Not recovered", lambda r: _counts(r["distribution"]["unrecovered"])),
    ("Identical", lambda r: "yes" if r["distribution"]["identical"] else "no"),
]


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(RESULTS.glob("*.json"))]
    README.write_text(embed(README.read_text(encoding="utf-8"), runs), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and the README table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
