"""Render CONTRACT.md: which Delivery Plus operations foood implements."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from foood.contract import CLAIMED, operations

ROOT = Path(__file__).resolve().parents[1]


def render() -> str:
    by_tag: dict[str, list[tuple[str, str, str, bool]]] = defaultdict(list)
    for op in operations():
        by_tag[op.tag].append((op.method, op.path, op.summary, (op.method, op.path) in CLAIMED))
    lines = [
        "# Contract coverage",
        "",
        "Operations of the Delivery Plus public API and whether `foood` implements them.",
        "Generated by `make contract` from `foood/contract.py`; do not edit by hand.",
        "",
    ]
    total = done = 0
    for tag, ops in sorted(by_tag.items()):
        n = sum(1 for *_, claimed in ops if claimed)
        total += len(ops)
        done += n
        lines += [
            f"## {tag} ({n}/{len(ops)})",
            "",
            "| | Method | Path | Summary |",
            "|---|---|---|---|",
        ]
        for method, path, summary, claimed in sorted(ops, key=lambda o: (o[1], o[0])):
            lines.append(f"| {'x' if claimed else ' '} | `{method}` | `{path}` | {summary} |")
        lines.append("")
    lines.insert(4, f"**{done} of {total} operations implemented.**")
    lines.insert(5, "")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "CONTRACT.md").write_text(render(), encoding="utf-8")
    print("wrote CONTRACT.md")
